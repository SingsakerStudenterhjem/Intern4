drop policy if exists "Users can delete penalties" on public.regi_penalties;
create policy "Users can delete penalties"
  on public.regi_penalties for delete
  to authenticated
  using (true);

drop policy if exists "Users can update penalties" on public.regi_penalties;
create policy "Users can update penalties"
  on public.regi_penalties for update
  to authenticated
