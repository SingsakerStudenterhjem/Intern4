create table if not exists public.regi_categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  required_hours numeric not null check (required_hours >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.regi_penalties (
  id bigint generated by default as identity primary key,
  user_uuid uuid not null references public.users(id) on delete cascade,
  hours numeric not null check (hours > 0),
  reason text not null,
  assigned_by_uuid uuid not null references public.users(id),
  created_at timestamptz not null default now()
);

alter table public.users
  add column if not exists regi_category_id bigint references public.regi_categories(id) on delete set null;

alter table public.regi_categories enable row level security;
alter table public.regi_penalties enable row level security;

drop policy if exists "Authenticated users can read regi categories" on public.regi_categories;
create policy "Authenticated users can read regi categories"
  on public.regi_categories for select
  to authenticated
  using (true);

drop policy if exists "Managers can insert regi categories" on public.regi_categories;
create policy "Managers can insert regi categories"
  on public.regi_categories for insert
  to authenticated
  with check (
    exists (
      select 1
      from public.users u
      join public.roles r on u.role_id = r.id
      where u.id = auth.uid()
        and r.name in ('Admin', 'Data', 'Regisjef')
    )
  );

drop policy if exists "Managers can update regi categories" on public.regi_categories;
create policy "Managers can update regi categories"
  on public.regi_categories for update
  to authenticated
  using (
    exists (
      select 1
      from public.users u
      join public.roles r on u.role_id = r.id
      where u.id = auth.uid()
        and r.name in ('Admin', 'Data', 'Regisjef')
    )
  );

drop policy if exists "Authenticated users can read penalties" on public.regi_penalties;
create policy "Authenticated users can read penalties"
  on public.regi_penalties for select
  to authenticated
  using (true);

drop policy if exists "Managers can insert penalties" on public.regi_penalties;
create policy "Managers can insert penalties"
